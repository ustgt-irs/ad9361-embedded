use arbitrary_int::{u2, u3, u4, u6};

#[derive(Debug, Clone, Copy)]
pub enum SynthLutType {
    Fdd,
    Tdd,
}
#[derive(Debug, Clone, Copy)]
pub enum LutFrequency {
    _40Mhz,
    _60Mhz,
    _80Mhz,
}

impl LutFrequency {
    #[inline]
    pub const fn get_fdd_lut(&self) -> &'static [SynthLut; SYNTH_LUT_SIZE] {
        match self {
            Self::_40Mhz => &fdd::LUT_40MHZ,
            Self::_60Mhz => &fdd::LUT_60MHZ,
            Self::_80Mhz => &fdd::LUT_80MHZ,
        }
    }

    #[inline]
    pub const fn get_tdd_lut(&self) -> &'static [SynthLut; SYNTH_LUT_SIZE] {
        match self {
            Self::_40Mhz => &tdd::LUT_40MHZ,
            Self::_60Mhz => &tdd::LUT_60MHZ,
            Self::_80Mhz => &tdd::LUT_80MHZ,
        }
    }
}

#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub enum RxGainTableType {
    /// Full gain table.
    Full,
    /// Split gain table.
    Split,
}

#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub enum RxGainTable {
    _0To1300Mhz,
    _1300To4000Mhz,
    _4000To6000Mhz,
}

impl RxGainTable {
    pub const fn new_for_lo_frequency(freq: u64) -> Self {
        if freq < 1_300_000_000 {
            Self::_0To1300Mhz
        } else if freq < 4_000_000_000 {
            Self::_1300To4000Mhz
        } else {
            Self::_4000To6000Mhz
        }
    }

    /// Get gain table.
    #[inline]
    pub fn gain_lut(&self, table_type: RxGainTableType) -> &'static [[u8; 3]] {
        match table_type {
            RxGainTableType::Full => match self {
                RxGainTable::_0To1300Mhz => &rx_gain::LUT_0_TO_1300_MHZ,
                RxGainTable::_1300To4000Mhz => &rx_gain::LUT_1300_TO_4000_MHZ,
                RxGainTable::_4000To6000Mhz => &rx_gain::LUT_4000_TO_6000_MHZ,
            },
            RxGainTableType::Split => match self {
                RxGainTable::_0To1300Mhz => &rx_split_gain::LUT_0_TO_1300_MHZ,
                RxGainTable::_1300To4000Mhz => &rx_split_gain::LUT_1300_TO_4000_MHZ,
                RxGainTable::_4000To6000Mhz => &rx_split_gain::LUT_4000_TO_6000_MHZ,
            },
        }
    }

    /// Absolute gain table.
    #[inline]
    pub fn abs_gain_lut(&self, table_type: RxGainTableType) -> &'static [i8] {
        match table_type {
            RxGainTableType::Full => match self {
                RxGainTable::_0To1300Mhz => &rx_gain_abs::LUT_0_TO_1300_MHZ,
                RxGainTable::_1300To4000Mhz => &rx_gain_abs::LUT_1300_TO_4000_MHZ,
                RxGainTable::_4000To6000Mhz => &rx_gain_abs::LUT_4000_TO_6000_MHZ,
            },
            RxGainTableType::Split => match self {
                RxGainTable::_0To1300Mhz => &rx_split_gain_abs::LUT_0_TO_1300_MHZ,
                RxGainTable::_1300To4000Mhz => &rx_split_gain_abs::LUT_1300_TO_4000_MHZ,
                RxGainTable::_4000To6000Mhz => &rx_split_gain_abs::LUT_4000_TO_6000_MHZ,
            },
        }
    }
}

